export function buildMarkdown(blueprint, idea) {
  const {
    ideaAnalysis, viabilityScorecard, aiDebate, customerDiscovery, swotAnalysis,
    portersFiveForces, marketSizing, marketResearch, customerPersona, productPlan,
    technicalArchitecture, businessStrategy, pitch, roadmap,
    goToMarket, launchChecklist, costEstimator, revenueSimulator,
    competitorWeaknessAnalysis,
  } = blueprint;

  const L = [];
  const push = (s = "") => L.push(s);

  push(`# Startup Blueprint`);
  push();
  push(`_Generated by IdeaPulse AI (https://idea-pulse-startup-validator.vercel.app) on ${formattedDate()}_`);
  push();

  push(`## Startup Idea`);
  push();
  push(idea || "_Not provided._");
  push();

  push(`## Multi-Agent VC Debate ("The VC War Room")`);
  if (ok(aiDebate)) {
    if (aiDebate.bull) {
      push(`### 🟢 AI 1: The Bull Partner (${aiDebate.bull.provider || "Groq Llama 3.3 70B"})`);
      push(`**Conviction:** ${aiDebate.bull.convictionScore || 85}/100`);
      push(`**Thesis:** ${aiDebate.bull.thesis}`);
      push(`**Unfair Wedge:** ${aiDebate.bull.unfairWedge}`);
      push();
    }
    if (aiDebate.bear) {
      push(`### 🔴 AI 2: The Bear Partner (${aiDebate.bear.provider || "OpenRouter DeepSeek V3"})`);
      push(`**Skepticism:** ${aiDebate.bear.skepticismScore || 85}/100`);
      push(`**Critique:** ${aiDebate.bear.thesis}`);
      push(`**CAC Trap:** ${aiDebate.bear.cacUnitEconomicsTrap}`);
      push();
    }
    if (aiDebate.judge) {
      push(`### ⚖️ AI 3: Chief Judge Ruling (${aiDebate.judge.provider || "Google Gemini"})`);
      push(`**Ruling:** ${aiDebate.judge.winningSide || "Consensus"} Advantage`);
      push(`**Verdict Synthesis:** ${aiDebate.judge.verdictSummary}`);
      push(`**#1 Lean Experiment:** ${aiDebate.judge.numberOneExperiment}`);
      push();
    }
  } else {
    push(`_Unavailable._`);
  }
  push();

  push(`## Venture Viability Scorecard`);
  if (ok(viabilityScorecard)) {
    push(`**Composite Viability Score:** ${viabilityScorecard.score}/100`);
    push(`**Verdict:** ${viabilityScorecard.verdict}`);
    push(`**Executive Thesis:** ${viabilityScorecard.verdictReasoning}`);
    push(`**Sub-Scores:**`);
    push(`- Market Demand: ${viabilityScorecard.marketDemandScore}/100`);
    push(`- Technical Feasibility: ${viabilityScorecard.technicalFeasibilityScore}/100`);
    push(`- Monetization Engine: ${viabilityScorecard.monetizationScore}/100`);
    push();
    if (okList(viabilityScorecard.fatalRiskTraps)) {
      push(`**Fatal Risk Traps:**`);
      viabilityScorecard.fatalRiskTraps.forEach((trap) => push(`- ${trap}`));
      push();
    }
  } else push(`_Unavailable._`);
  push();

  push(`## Lean Customer Discovery ("Mom Test")`);
  if (ok(customerDiscovery)) {
    if (okList(customerDiscovery.interviewQuestions)) {
      push(`**Mom Test Interview Questions:**`);
      customerDiscovery.interviewQuestions.forEach((q, i) => push(`${i + 1}. ${q}`));
      push();
    }
    if (okList(customerDiscovery.redFlags)) {
      push(`**False-Positive Red Flags:**`);
      customerDiscovery.redFlags.forEach((rf) => push(`- ✕ ${rf}`));
      push();
    }
    if (okList(customerDiscovery.willingnessToPaySignals)) {
      push(`**Willingness-to-Pay Commitment Tests:**`);
      customerDiscovery.willingnessToPaySignals.forEach((wtp) => push(`- ✓ ${wtp}`));
      push();
    }
  } else push(`_Unavailable._`);
  push();

  push(`## Strategic Frameworks (SWOT & Porter's Five Forces)`);
  if (ok(swotAnalysis)) {
    push(`### SWOT (Strengths, Weaknesses, Opportunities, Threats) Matrix`);
    push(`**Strengths:**`);
    (swotAnalysis.strengths || []).forEach((s) => push(`- ${s}`));
    push(`**Weaknesses:**`);
    (swotAnalysis.weaknesses || []).forEach((w) => push(`- ${w}`));
    push(`**Opportunities:**`);
    (swotAnalysis.opportunities || []).forEach((o) => push(`- ${o}`));
    push(`**Threats:**`);
    (swotAnalysis.threats || []).forEach((t) => push(`- ${t}`));
    push();
  }
  if (ok(portersFiveForces)) {
    push(`### Porter's Five Forces Industry Analysis`);
    push(`- Buyer Bargaining Power: [${portersFiveForces.buyerPower?.level || "Moderate"}] ${portersFiveForces.buyerPower?.analysis || ""}`);
    push(`- Supplier Bargaining Power: [${portersFiveForces.supplierPower?.level || "Low"}] ${portersFiveForces.supplierPower?.analysis || ""}`);
    push(`- Competitive Rivalry: [${portersFiveForces.competitiveRivalry?.level || "Moderate"}] ${portersFiveForces.competitiveRivalry?.analysis || ""}`);
    push(`- Threat of Substitutes: [${portersFiveForces.threatOfSubstitutes?.level || "Moderate"}] ${portersFiveForces.threatOfSubstitutes?.analysis || ""}`);
    push(`- Threat of New Entrants: [${portersFiveForces.threatOfNewEntry?.level || "Moderate"}] ${portersFiveForces.threatOfNewEntry?.analysis || ""}`);
    push();
  }
  push();

  push(`## Market Sizing Architecture (TAM / SAM / SOM)`);
  if (ok(marketSizing)) {
    push(`- **TAM (Total Addressable Market):** ${marketSizing.tam?.value || "₹1.15 Lakh Cr"} — ${marketSizing.tam?.description || ""}`);
    push(`- **SAM (Serviceable Available Market):** ${marketSizing.sam?.value || "₹34,000 Cr"} — ${marketSizing.sam?.description || ""}`);
    push(`- **SOM (Serviceable Obtainable Market):** ${marketSizing.som?.value || "₹560 Cr"} — ${marketSizing.som?.description || ""}`);
  } else push(`_Unavailable._`);
  push();

  push(`## Idea Analysis`);
  if (ok(ideaAnalysis)) {
    push(`**Problem:** ${ideaAnalysis.problem}`);
    push();
    push(`**Goal:** ${ideaAnalysis.goal}`);
    push();
    push(`**Domain:** ${ideaAnalysis.domain}`);
    push();
    push(`**Feasibility:** ${ideaAnalysis.feasibility}`);
  } else push(`_Unavailable._`);
  push();

  push(`## Market Intelligence`);
  if (ok(marketResearch)) {
    push(`**Competitors:**`);
    (marketResearch.competitors || []).forEach((c) => push(`- ${c}`));
    push();
    push(`**Opportunities:**`);
    (marketResearch.opportunities || []).forEach((c) => push(`- ${c}`));
    push();
    push(`**Market Demand:** ${marketResearch.marketDemand}`);
  } else push(`_Unavailable._`);
  push();

  push(`## Customer Persona`);
  if (ok(customerPersona)) {
    push(`**Target Users:**`);
    (customerPersona.targetUsers || []).forEach((c) => push(`- ${c}`));
    push();
    push(`**Pain Points:**`);
    (customerPersona.painPoints || []).forEach((c) => push(`- ${c}`));
    push();
    push(`**User Profile:** ${customerPersona.userProfile}`);
  } else push(`_Unavailable._`);
  push();

  push(`## Product Planning`);
  if (ok(productPlan)) {
    push(`**MVP Features:**`);
    (productPlan.mvpFeatures || []).forEach((c) => push(`- ${c}`));
    push();
    push(`**Future Features:**`);
    (productPlan.futureFeatures || []).forEach((c) => push(`- ${c}`));
    push();
    push(`**Development Priority:** ${productPlan.developmentPriority}`);
  } else push(`_Unavailable._`);
  push();

  push(`## Tech Stack`);
  if (ok(technicalArchitecture)) {
    push(`| Layer | Recommendation |`);
    push(`|---|---|`);
    push(`| Frontend | ${technicalArchitecture.frontend} |`);
    push(`| Backend | ${technicalArchitecture.backend} |`);
    push(`| Database | ${technicalArchitecture.database} |`);
    push(`| Hosting | ${technicalArchitecture.hosting} |`);
    push(`| AI APIs | ${technicalArchitecture.aiApis} |`);
    push();
    push(`**Architecture Overview:** ${technicalArchitecture.architectureOverview}`);
  } else push(`_Unavailable._`);
  push();

  push(`## Business Strategy`);
  if (ok(businessStrategy)) {
    push(`**Revenue Model:** ${businessStrategy.revenueModel}`);
    push();
    push(`**Pricing Idea:** ${businessStrategy.pricingIdea}`);
    push();
    push(`**Marketing Channels:**`);
    (businessStrategy.marketingChannels || []).forEach((c) => push(`- ${c}`));
  } else push(`_Unavailable._`);
  push();

  push(`## Cost Estimator`);
  if (ok(costEstimator)) {
    push(`| Item | Monthly Cost | Free Tier OK | Note |`);
    push(`|---|---|---|---|`);
    COST_KEYS.forEach((k) => {
      const item = costEstimator[k];
      if (item) push(`| ${COST_LABELS[k]} | ${item.monthlyCost} | ${item.freeTierSufficient ? "Yes" : "No"} | ${item.note || ""} |`);
    });
    push();
    push(`**Estimated Monthly Total:** ${costEstimator.estimatedMonthlyCost}`);
    push();
    push(`**Estimated Yearly Total:** ${costEstimator.estimatedYearlyCost}`);
  } else push(`_Unavailable._`);
  push();

  push(`## Revenue Simulator`);
  if (ok(revenueSimulator)) {
    if (revenueSimulator.pricingAssumption) {
      push(`_Assumption: ${revenueSimulator.pricingAssumption}_`);
      push();
    }
    push(`| Users | Monthly Revenue | Annual Revenue |`);
    push(`|---|---|---|`);
    (revenueSimulator.projections || []).forEach((p) => {
      push(`| ${p.users} | ${p.monthlyRevenue} | ${p.annualRevenue} |`);
    });
  } else push(`_Unavailable._`);
  push();

  push(`## Competitor Analysis`);
  if (okList(competitorWeaknessAnalysis)) {
    competitorWeaknessAnalysis.forEach((c) => {
      push(`### ${c.competitor}`);
      push(`**Weaknesses:**`);
      (c.weaknesses || []).forEach((w) => push(`- ${w}`));
      push();
      push(`**Missed Opportunities:**`);
      (c.missedOpportunities || []).forEach((w) => push(`- ${w}`));
      push();
      push(`**Suggested Differentiation:** ${c.suggestedDifferentiation}`);
      push();
    });
  } else push(`_Unavailable._`);
  push();

  push(`## Go-To-Market Strategy`);
  if (ok(goToMarket)) {
    push(`**Target Audience:** ${goToMarket.targetAudience}`);
    push();
    (goToMarket.platforms || []).forEach((p) => {
      const name = typeof p === "string" ? p : (p?.name || p?.platform || "Channel");
      const why = typeof p === "string" ? "" : (p?.why || p?.strategy || p?.tactic || "");
      push(why ? `- **${name}** — ${why}` : `- **${name}**`);
    });
    push();
    push(`**LinkedIn Search Strategy:**`);
    (goToMarket.linkedInSearchStrategy || []).forEach((q) => push(`- ${q}`));
    push();
    const coldEmail = safeTemplateStr(goToMarket.coldEmailTemplate || goToMarket.coldEmail);
    const linkedInDm = safeTemplateStr(goToMarket.linkedInDmTemplate || goToMarket.linkedInDm);
    const redditPost = safeTemplateStr(goToMarket.redditLaunchPost || goToMarket.redditPost);
    const twitterPost = safeTemplateStr(goToMarket.twitterLaunchPost || goToMarket.twitterPost || goToMarket.xPost);

    if (coldEmail) {
      push(`**Cold Email Template:**`);
      push("```");
      push(coldEmail);
      push("```");
      push();
    }
    if (linkedInDm) {
      push(`**LinkedIn DM Template:**`);
      push("```");
      push(linkedInDm);
      push("```");
      push();
    }
    if (redditPost) {
      push(`**Reddit Launch Post:**`);
      push("```");
      push(redditPost);
      push("```");
      push();
    }
    if (twitterPost) {
      push(`**X (Twitter) Launch Post:**`);
      push("```");
      push(twitterPost);
      push("```");
      push();
    }
  } else push(`_Unavailable._`);
  push();

  push(`## Launch Checklist`);
  if (okList(launchChecklist)) {
    launchChecklist.forEach((item) => push(`- [ ] ${item}`));
  } else push(`_Unavailable._`);
  push();

  push(`## Investor Pitch`);
  if (ok(pitch)) {
    push(`**Elevator Pitch:** ${pitch.elevatorPitch}`);
    push();
    push(`**Executive Summary:** ${pitch.executiveSummary}`);
  } else push(`_Unavailable._`);
  push();

  push(`## Startup Roadmap`);
  if (ok(roadmap)) {
    (roadmap.milestones || []).forEach((m) => {
      push(`### ${m.week} — ${m.title}`);
      (m.tasks || []).forEach((t) => push(`- ${t}`));
      push();
    });
    push(`**Launch Plan:** ${roadmap.launchPlan}`);
  } else push(`_Unavailable._`);

  return L.join("\n");
}

export function downloadMarkdown(blueprint, idea) {
  const md = buildMarkdown(blueprint, idea);
  const blob = new Blob([md], { type: "text/markdown;charset=utf-8" });
  const url = URL.createObjectURL(blob);
  const a = document.createElement("a");
  a.href = url;
  a.download = "ideapulse-blueprint.md";
  document.body.appendChild(a);
  a.click();
  a.remove();
  URL.revokeObjectURL(url);
}

