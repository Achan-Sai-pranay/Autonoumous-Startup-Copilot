// lib/promptPackGenerator.js
// ---------------------------------------------------------------------------
// 1-Click AI Prompt Pack Synthesizer for Cursor, Bolt.new, Lovable.dev & v0
// Bridges the gap between idea validation and shipping working code.
// Synthesizes all 7 Lean Startup blueprint stages into actionable prompts.
// ---------------------------------------------------------------------------

function safe(v, fallback = "") {
  if (v === null || v === undefined) return fallback;
  if (typeof v === "string") return v.trim() || fallback;
  if (Array.isArray(v)) return v.filter(Boolean).join(", ") || fallback;
  if (typeof v === "object") return JSON.stringify(v);
  return String(v);
}

function safeArr(arr, fallback = []) {
  if (Array.isArray(arr) && arr.length > 0) return arr;
  return fallback;
}

/**
 * Generates the complete prompt pack across Cursor, Lovable, Bolt, and v0
 * @param {string} idea - Startup thesis/idea
 * @param {object} blueprint - Full 7-stage LaunchPilot blueprint
 * @returns {object} promptPack
 */
export function generatePromptPack(idea, blueprint = {}) {
  const cleanIdea = safe(idea, "Autonomous Startup Application");
  const problem = safe(blueprint?.ideaAnalysis?.problem, "Manual, fragmented, and inefficient workflows.");
  const solution = safe(blueprint?.ideaAnalysis?.solution, "Instant, AI-powered automated platform delivering speed and focus.");
  const targetAudience = safe(blueprint?.customerPersona?.personaName, "Founders, builders, and modern operators");
  const viabilityScore = safe(blueprint?.ideaAnalysis?.viabilityScore, "85");

  // Stage 04: Market & Competitors
  const competitors = safeArr(blueprint?.marketResearch?.competitors, ["Legacy Enterprise Incumbents", "Manual Spreadsheets"]).join(", ");
  const wedge = safe(blueprint?.ideaAnalysis?.unfairAdvantage || blueprint?.businessStrategy?.wedge, "Autonomous real-time execution with transparent self-serve pricing.");

  // Stage 05: Product & MVP
  const techArch = blueprint?.technicalArchitecture || {};
  const frontendStack = safe(techArch?.frontend, "React 18 + Vite + Tailwind CSS + Lucide Icons");
  const backendStack = safe(techArch?.backend, "Node.js / Express or FastAPI");
  const dbStack = safe(techArch?.database, "PostgreSQL / Supabase");
  const mvpFeatures = safeArr(blueprint?.productPlan?.mvpFeatures, [
    "Core user dashboard with real-time analytics",
    "Instant input-to-output workflow generator",
    "Self-serve billing and subscription management",
    "One-click sharing and export capabilities",
  ]);

  // Stage 06: Financials & Pricing
  const pricingModel = safe(blueprint?.businessStrategy?.pricingStrategy, "Monthly subscription with self-service tiers (Starter & Pro)");

  // Stage 07: GTM
  const launchHook = safe(blueprint?.pitch?.elevatorPitch, `${cleanIdea} — built to solve ${problem}`);

  // 1. .cursorrules file content
  const cursorRules = `# .cursorrules — Project Standards for ${cleanIdea}
# Generated by LaunchPilot AI (Viability Score: ${viabilityScore}/100)

You are an expert senior full-stack engineer and product designer. Build a production-ready, beautiful web application for:
"${cleanIdea}"

## 1. Product Context
- Core Problem: ${problem}
- Core Solution: ${solution}
- Primary Audience: ${targetAudience}
- Core Differentiation Wedge: ${wedge}

## 2. Tech Stack Requirements
- Frontend: ${frontendStack}
- Backend/API: ${backendStack}
- Database: ${dbStack}
- Styling: Tailwind CSS (Mobile-first, responsive, dark/light contrast)
- Icons: lucide-react

## 3. Engineering & Architecture Rules
- Follow Clean Architecture: separate UI components, API clients, and business logic.
- Avoid bulky monostores: use lightweight React hooks and local state where possible.
- Never write placeholder "TODO" comments in place of core logic. Implement complete working features.
- Provide graceful empty states, inline loading spinners, and actionable error toasts for all network actions.
- Accessibility: Ensure semantic HTML, visible keyboard focus rings, and proper ARIA labels.

## 4. MVP Sprint 1 Scope (Mandatory Features)
${mvpFeatures.map((feat, idx) => `${idx + 1}. ${feat}`).join("\n")}

## 5. UI/UX Style Guidelines
- Aesthetic: Apple-style minimalism — clean sans-serif typography (Plus Jakarta Sans or Inter), 1px subtle borders (border-slate-200/80), frosted glass overlays (backdrop-blur-md), and deliberate orange or indigo CTA contrast.
- Performance: Keep bundle sizes small; lazy load routes and heavy charts.
`.trim();

  // 2. Lovable & Bolt.new Kick-off Master Prompt
  const lovableBoltPrompt = `Build a complete, production-grade web application for:
"${cleanIdea}"

### Executive Brief
- Problem to solve: ${problem}
- How it solves it: ${solution}
- Target User: ${targetAudience}
- Competitors to disrupt: ${competitors}
- Winning Wedge: ${wedge}
- Monetization: ${pricingModel}

### Tech Stack
- Frontend: React + Vite + Tailwind CSS + Lucide Icons
- State: Local React state + localStorage persistence (with Supabase ready hooks)
- Responsive: Fully fluid on 375px mobile, tablet, and 1440px desktop.

### MVP Features to Implement
${mvpFeatures.map((feat, idx) => `${idx + 1}. ${feat}`).join("\n")}

### Essential Pages & Views
1. Landing Page / Hero:
   - High-conversion Apple-style hero section with headline: "${launchHook}"
   - Interactive live demo preview widget
   - Feature highlights and Social Proof / Viability score (${viabilityScore}/100)
   - Transparent Pricing Cards (Starter & Scale tiers)
2. App Workspace:
   - Clean navigation sidebar with Projects, Analytics, Settings
   - Main workspace with input controls and interactive output cards
   - Action toolbar: Export to PDF, Copy link, and Settings
3. Settings & Billing:
   - Plan status widget and quota telemetry.

### Design System
- Clean, Apple-inspired layout: off-white background (#f8fafc or #fafafa), dark charcoal typography (#0f172a), subtle borders (#e2e8f0), and vibrant accent (#ea580c or #2563eb).
- Use Lucide React icons for all visual cues.
- Build fully functioning interactive components with mock data so the app is instantly usable out of the box!
`.trim();

  // 3. v0.dev UI Prompt
  const v0Prompt = `Create a modern, ultra-clean Apple-style dashboard for "${cleanIdea}".

Features to display:
- Problem: ${problem}
- Core MVP capabilities: ${mvpFeatures.slice(0, 3).join(", ")}
- Top bar with workspace switcher, search input, and "Export" CTA button.
- Bento grid layout featuring:
  1. Primary metric hero card (Viability: ${viabilityScore}/100) with a gradient ring gauge.
  2. Main interactive workspace card for generating and previewing outputs.
  3. Quick actions card with copy, share, and settings triggers.
- Use Tailwind CSS with neutral-slate tones, subtle 1px border cards, and terracotta/orange primary action buttons.
`.trim();

  // 4. Master 7-Stage System Prompt
  const masterSystemPrompt = `You are the lead technical co-founder building "${cleanIdea}".
Here is the complete 7-stage institutional blueprint context validated by LaunchPilot AI (Score: ${viabilityScore}/100):

[STAGE 1: EXECUTIVE BRIEF]
Problem: ${problem}
Solution: ${solution}
Target Market: ${targetAudience}

[STAGE 2: VC COMMITTEE VERDICT]
Consensus: Strong market timing with focus on defensibility.
Wedge: ${wedge}

[STAGE 3: CUSTOMER & PAIN POINTS]
Primary Customer: ${targetAudience}
Key Frustrations: ${safe(blueprint?.customerPersona?.painPoints, "Tired of slow, bloated legacy options.")}

[STAGE 4: MARKET & DEFICIENCY]
Incumbents: ${competitors}
Weakness: High churn, complex onboarding, and inflexible pricing.

[STAGE 5: PRODUCT & MVP SCOPE]
Core Features:
${mvpFeatures.map((f) => `- ${f}`).join("\n")}
Tech Stack: ${frontendStack} | ${backendStack} | ${dbStack}

[STAGE 6: FINANCIAL MODEL]
Pricing: ${pricingModel}

[STAGE 7: LAUNCH HOOK]
Pitch: ${launchHook}

TASK:
Write the complete code architecture for the MVP. Start with project directory structure, core data models, and primary reactive components.
`.trim();

  return {
    cursorRules,
    lovableBoltPrompt,
    v0Prompt,
    masterSystemPrompt,
  };
}
